#!/usr/bin/env python3
"""zero-gap-coverage-measure.py - REAL-RUN measurer for the coverage map (feature 010, task T053).

WHAT IT DOES
  For each (subject x test kind) cell it can map to a cheap, bounded, offline invocation, it RUNS that
  invocation and records what executed: the command, the exit code, passed/failed/skipped case counts,
  and a captured evidence file. Output (both tracked, both regenerated by this script only):
    docs/zero-gap/coverage-measured.tsv        subject kind status cases failed rc evidence cmd
                                               (failed and rc are the REAL worst values, never hard-coded)
    docs/zero-gap/coverage-evidence/*.txt      one captured-output excerpt per measured cell
  scripts/zero-gap-coverage.sh (T052 generator) CONSUMES coverage-measured.tsv: it re-validates every
  row (evidence file exists, cases > 0 for `check`) through its own decide_status() zero-case rule, so
  status is never hand-written into coverage.tsv.

STATUS RULES (FR-010/FR-011)
  check              invocation ran, compiled, executed >= 1 case AND failed == 0 AND rc == 0.
  check-red          invocation executed >= 1 case but a case failed or rc != 0: the kind is APPLIED but
                     not PROVEN, so it is NOT coverage (FR-010/FR-011/SC-005). The generator may upgrade
                     it to `designed-red` only for a gate declared in docs/zero-gap/designed-red.tsv whose
                     declared rc equals the measured rc; the measurer never decides that.
  gap                invocation ran and executed 0 cases, or the kind has no invocation on this subject.
  could-not-run:<t>  the tool/dependency needed is absent or the build failed (never a pass).
  n/a:<reason>       declared not applicable with a measured reason (e.g. no UI surface => accessibility).

SAFETY
  Heavy jobs run ONE AT A TIME under `systemd-run --user --scope -p MemoryMax=8G` when available,
  GOPROXY=off, GOFLAGS=-mod=mod is NOT used (read-only module cache). Never touches live services:
  go test is run only on test directories; nothing is started by this script except what the tests
  themselves start in-process.

Usage:  zero-gap-coverage-measure.py [--only SUBJECT[:KIND]] [--timeout SEC] [--root DIR]
"""
import argparse, datetime, hashlib, json, os, re, shutil, subprocess, sys, time

KIND_DIRS = {
    'integration': ['tests/integration'],
    'e2e': ['tests/e2e'],
    'security': ['tests/security'],
    'perf-load': ['tests/benchmark', 'tests/performance', 'tests/load'],
    'stress-chaos': ['tests/stress', 'tests/chaos'],
    'contract': ['tests/contract'],
    'regression': ['tests/regression'],
    'determinism': ['tests/determinism'],
}
ALL_KINDS = ['unit', 'integration', 'e2e', 'contract', 'security', 'accessibility', 'perf-load',
             'stress-chaos', 'mutation', 'determinism', 'regression', 'manual-qa-readiness']

ap = argparse.ArgumentParser()
ap.add_argument('--only', default='')
ap.add_argument('--timeout', type=int, default=240)
ap.add_argument('--root', default=os.path.realpath(os.path.join(os.path.dirname(__file__), '..')))
ap.add_argument('--selftest', action='store_true', help='assert the pure aggregation/classification/binding functions, run nothing')
a = ap.parse_args()
HAVE_SD = shutil.which('systemd-run') is not None


def classify(cases, failed, rc):
    """FR-010/FR-011: covered only when cases>0 AND failed==0 AND rc==0; cases>0 otherwise is red."""
    if cases <= 0:
        return 'gap'
    return 'check' if (failed == 0 and rc == 0) else 'check-red'


def aggregate_unit(results):
    """results: one dict per module that ran tests (rc, p, f, s). Returns the REAL totals: summed
    passed/failed/skipped and the WORST (largest) exit code - never a hard-coded 0."""
    return {'passed': sum(r['p'] for r in results), 'failed': sum(r['f'] for r in results),
            'skipped': sum(r['s'] for r in results), 'rc': max([r['rc'] for r in results] or [0])}


_BIND = {}


def binding():
    """head= (git HEAD), tree= (sha256 of HEAD + `git status --porcelain` = the exact tree state that was
    measured), ts= (UTC). head/tree are computed once per run; ts per record."""
    if 'head' not in _BIND:
        def g(*args):
            return subprocess.run(['git', '-C', ROOT] + list(args), stdout=subprocess.PIPE, stderr=subprocess.DEVNULL).stdout.decode()
        head = g('rev-parse', 'HEAD').strip() or '0' * 40
        _BIND['head'] = head
        _BIND['tree'] = hashlib.sha256((head + '\n' + g('status', '--porcelain=v1')).encode()).hexdigest()
    return _BIND['head'], _BIND['tree'], datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')


def evidence_header(subj, kind, status, cases, failed, rc, cmd, extra, head, tree, ts):
    return ('subject=%s kind=%s status=%s cases=%s failed=%s rc=%s\nhead=%s tree=%s ts=%s\ncmd=%s\n%s\n---\n'
            % (subj, kind, status, cases, failed, rc, head, tree, ts, cmd, extra))


def gate_failed(rc, out):
    """Failed-case count of a root GATE script, best effort. A gate that exits 0 has no failed result of its
    own: FAIL/failed lines in its output belong to its golden-bad (must-detect) arms and are NOT failures.
    Only a non-zero rc makes the parsed count meaningful; rc itself stays authoritative either way."""
    if rc == 0:
        return 0
    return max([int(x) for x in re.findall(r'(\d+) (?:FAIL(?:ED)?|DRIFT|DEFECT|failed)\b', out)] or [0])


def selftest():
    ok = True

    def chk(name, cond):
        nonlocal ok
        print('  %s %s' % ('PASS' if cond else 'FAIL', name))
        ok = ok and cond
    agg = aggregate_unit([{'rc': 0, 'p': 10, 'f': 0, 's': 1}, {'rc': 1, 'p': 57, 'f': 62, 's': 0}])
    chk('aggregate_unit keeps the worst rc (1) from a module with 62 failed cases, not 0', agg['rc'] == 1 and agg['failed'] == 62 and agg['passed'] == 67)
    chk('aggregate_unit: a timeout rc 124 outranks rc 1', aggregate_unit([{'rc': 1, 'p': 1, 'f': 1, 's': 0}, {'rc': 124, 'p': 0, 'f': 0, 's': 0}])['rc'] == 124)
    chk('aggregate_unit of all-green modules is rc 0', aggregate_unit([{'rc': 0, 'p': 3, 'f': 0, 's': 0}])['rc'] == 0)
    chk('classify: 119 cases, 62 failed => check-red', classify(119, 62, 1) == 'check-red')
    chk('classify: cases>0 failed 0 rc 1 => check-red', classify(5, 0, 1) == 'check-red')
    chk('classify: cases>0 failed 0 rc 0 => check', classify(5, 0, 0) == 'check')
    chk('classify: zero cases => gap', classify(0, 0, 0) == 'gap')
    chk('gate_failed: rc 0 with a golden-bad arm printing "4 FAIL" is NOT 4 failures', gate_failed(0, '2 PASS / 4 FAIL / 0 SKIP of 6') == 0)
    chk('gate_failed: rc 1 reports the parsed failed count', gate_failed(1, '9 PASS / 3 FAIL') == 3)
    h = evidence_header('s', 'unit', 'check', 3, 1, 1, 'c', 'x', 'a' * 40, 'b' * 64, '2026-10-12T00:00:00Z')
    first, second = h.splitlines()[:2]
    chk('evidence header line 1 binds subject/kind/cases/failed/rc', 'subject=s kind=unit' in first and 'cases=3 failed=1 rc=1' in first)
    chk('evidence header line 2 binds head/tree/ts', second == 'head=%s tree=%s ts=2026-10-12T00:00:00Z' % ('a' * 40, 'b' * 64))
    print('measure selftest: %s' % ('ok' if ok else 'FAILED'))
    return ok


if a.selftest:
    sys.exit(0 if selftest() else 1)

ROOT = a.root
EVD = os.path.join(ROOT, 'docs/zero-gap/coverage-evidence')
OUT = os.path.join(ROOT, 'docs/zero-gap/coverage-measured.tsv')
os.makedirs(EVD, exist_ok=True)


def slug(s):
    return re.sub(r'[^A-Za-z0-9._-]+', '_', s)


def run(cmd, cwd, timeout):
    """Run cmd (list) bounded; returns (rc, stdout+stderr, seconds). rc 124 on timeout."""
    full = cmd
    if HAVE_SD:
        full = ['systemd-run', '--user', '--scope', '--quiet', '-p', 'MemoryMax=8G', '-p', 'TasksMax=4096'] + cmd
    env = dict(os.environ, GOPROXY='off', GOFLAGS='-mod=readonly', LC_ALL='C', GOMAXPROCS='4')
    t = time.time()
    try:
        p = subprocess.run(['timeout', '-k', '10', str(timeout)] + full, cwd=cwd, env=env,
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)
        return p.returncode, p.stdout.decode(errors='replace'), time.time() - t
    except Exception as e:  # noqa
        return 125, 'exec error: %s' % e, time.time() - t


def go_json_counts(out, bench_mode=False):
    passed = failed = skipped = 0
    build_fail = False
    for line in out.splitlines():
        if line.startswith('{'):
            try:
                ev = json.loads(line)
            except Exception:
                continue
            if ev.get('Test'):
                act = ev.get('Action')
                if act == 'pass': passed += 1
                elif act == 'fail': failed += 1
                elif act == 'skip': skipped += 1
            if ev.get('Action') == 'fail' and not ev.get('Test') and 'build failed' in (ev.get('Output') or ''):
                build_fail = True
        elif 'build failed' in line or 'cannot find module' in line or 'no required module' in line \
                or 'GOPROXY list is not the empty string' in line or 'missing go.sum' in line:
            build_fail = True
    if 'module lookup disabled' in out or '[setup failed]' in out or '"Action":"build-fail"' in out or 'FailedBuild' in out:
        build_fail = True
    if bench_mode:
        passed = max(passed, len(re.findall(r'ns/op', out)))
    return passed, failed, skipped, build_fail


rows = []


def record(subj, kind, status, cases, rc, cmd, out, extra='', failed=0):
    # FR-010/FR-011: a `check` that is red (failed>0 or rc!=0) is recorded as `check-red`, never `check`.
    if status == 'check':
        status = classify(cases, failed, rc)
    ev = ''
    if out is not None:
        fn = 'docs/zero-gap/coverage-evidence/%s__%s.txt' % (slug(subj), kind)
        body = out
        lines = body.splitlines()
        if len(lines) > 60:
            body = '\n'.join(lines[:10] + ['... [%d lines elided] ...' % (len(lines) - 50)] + lines[-40:])
        head, tree, ts = binding()
        hdr = evidence_header(subj, kind, status, cases, failed, rc, cmd, extra, head, tree, ts)
        # scrub anything that looks like a credential assignment (CONST-042)
        body = re.sub(r'(?i)(password|secret|token|api[_-]?key)\s*[=:]\s*\S+', r'\1=<scrubbed>', body)
        with open(os.path.join(ROOT, fn), 'w') as fh:
            fh.write(hdr + body + '\n')
        ev = fn
    rows.append((subj, kind, status, str(cases), str(failed), str(rc), ev, cmd))
    print('  %-34s %-18s %-22s cases=%-5s failed=%-4s rc=%s' % (subj, kind, status, cases, failed, rc), flush=True)


def go_cell(subj, kind, gomod_dir, pkgs, tags=None):
    cmd = ['go', 'test', '-count=1', '-json']
    if kind == 'perf-load':
        cmd += ['-run', '.', '-bench', '.', '-benchtime', '1x']
    if tags:
        cmd += ['-tags', tags]
    cmd += pkgs
    rc, out, dt = run(cmd, gomod_dir, a.timeout)
    p, f, s, bf = go_json_counts(out, kind == 'perf-load')
    shown = ' '.join(cmd)
    if rc == 124 or rc == 137:
        record(subj, kind, 'could-not-run:timeout', 0, rc, shown, out, 'timed out after %ss' % a.timeout)
    elif bf and p + f == 0:
        record(subj, kind, 'could-not-run:go-build', 0, rc, shown, out)
    elif p + f > 0:
        record(subj, kind, 'check', p + f, rc, shown, out, 'passed=%d failed=%d skipped=%d seconds=%.1f' % (p, f, s, dt), failed=f)
    else:
        record(subj, kind, 'gap', 0, rc, shown, out, 'passed=0 failed=0 skipped=%d' % s)


def gomods(subj):
    """Own, TRACKED go.mod directories of a subject (never harvested third-party copies, vendor,
    node_modules, upstream-contributions), shortest path first, capped at 6 modules."""
    base = os.path.join(ROOT, subj)
    ls = subprocess.run(['git', '-C', base, 'ls-files', '--', 'go.mod', '**/go.mod'], stdout=subprocess.PIPE).stdout.decode().split('\n')
    skip = ('_harvest/', 'vendor/', 'node_modules/', 'upstream-contributions/', 'output/', '/venv/')
    res = [os.path.join(base, os.path.dirname(l)) for l in ls if l and not any(x in l for x in skip)]
    res = sorted(set(os.path.normpath(r) for r in res), key=lambda r: (len(r), r))
    return res[:6]


def measure_module(subj):
    base = os.path.join(ROOT, subj)
    mods = gomods(subj)
    want = lambda k: (not a.only) or a.only in (subj, '%s:%s' % (subj, k))
    # accessibility: n/a only when the module has no UI surface (measured)
    ui = subprocess.run("git -C %s ls-files | grep -Ei '\\.(html|css|tsx|jsx|vue|svelte)$' | head -1" % subj,
                        shell=True, cwd=ROOT, stdout=subprocess.PIPE).stdout.decode().strip()
    if want('accessibility'):
        if not ui:
            record(subj, 'accessibility', 'n/a:no tracked html/css/tsx/jsx/vue/svelte UI source in this module (git ls-files probe)', 0, 0, 'git ls-files | grep UI extensions', None)
        else:
            record(subj, 'accessibility', 'gap', 0, 0, 'git ls-files | grep UI extensions => %s' % ui, None)
    # manual QA readiness: a tracked docs/qa with files inside the module
    if want('manual-qa-readiness'):
        n = subprocess.run("git -C %s ls-files -- docs/qa | wc -l" % subj, shell=True, cwd=ROOT, stdout=subprocess.PIPE).stdout.decode().strip()
        if n.isdigit() and int(n) > 0:
            record(subj, 'manual-qa-readiness', 'check', int(n), 0, 'git -C %s ls-files -- docs/qa' % subj,
                   subprocess.run("git -C %s ls-files -- docs/qa | head -40" % subj, shell=True, cwd=ROOT, stdout=subprocess.PIPE).stdout.decode(),
                   'tracked files in module docs/qa: %s' % n)
        else:
            record(subj, 'manual-qa-readiness', 'gap', 0, 0, 'git -C %s ls-files -- docs/qa' % subj, None)
    if not mods:
        return
    top = mods[0]
    # unit: every module's non-tests/ packages, -short, one module at a time; counts summed.
    if want('unit'):
        tp = tf = ts = 0; outs = []; cmds = []; nomod_build = 0; ran = 0; results = []
        for mdir in mods:
            rc, out, dt = run(['go', 'list', './...'], mdir, 120)
            pk = [l for l in out.splitlines() if re.match(r'^[A-Za-z0-9._-]+(/[A-Za-z0-9._/-]+)?$', l.strip()) and ' ' not in l]
            pk = [x for x in pk if '/tests/' not in x and not x.endswith('/tests') and '/e2e' not in x and '/cmd/' not in x and '/gates/' not in x]
            if not pk:
                outs.append('## %s: go list rc=%s, no packages\n%s' % (mdir, rc, out[-600:]))
                continue
            cmd = ['go', 'test', '-count=1', '-json', '-short'] + pk
            rc2, o2, dt2 = run(cmd, mdir, a.timeout)
            p_, f_, s_, bf_ = go_json_counts(o2)
            tp += p_; tf += f_; ts += s_; ran += 1
            results.append({'rc': rc2, 'p': p_, 'f': f_, 's': s_})
            if rc2 in (124, 137): nomod_build += 1
            cmds.append('(cd %s && go test -count=1 -json -short <%d pkgs>)' % (os.path.relpath(mdir, ROOT), len(pk)))
            outs.append('## %s: rc=%s passed=%d failed=%d skipped=%d seconds=%.1f build_fail=%s\n%s' % (os.path.relpath(mdir, ROOT), rc2, p_, f_, s_, dt2, bf_, '\n'.join(l for l in o2.splitlines() if not l.startswith('{"Time"'))[-1500:]))
        joined = '\n'.join(outs)
        shown = '; '.join(cmds) or 'go list ./...'
        agg = aggregate_unit(results)
        if tp + tf > 0:
            record(subj, 'unit', 'check', tp + tf, agg['rc'], shown, joined,
                   'passed=%d failed=%d skipped=%d over %d module(s); worst module rc=%d' % (tp, tf, ts, ran, agg['rc']), failed=tf)
        elif ran == 0:
            record(subj, 'unit', 'could-not-run:go-list', 0, 1, shown, joined)
        elif nomod_build:
            record(subj, 'unit', 'could-not-run:timeout', 0, 124, shown, joined)
        else:
            record(subj, 'unit', 'gap', 0, 0, shown, joined, 'zero cases executed')
    for kind, dirs in KIND_DIRS.items():
        if not want(kind):
            continue
        found = [(m, d) for m in mods for d in dirs if os.path.isdir(os.path.join(m, d))]
        if not found:
            continue
        # run all found directories of this kind in the first module that has them
        m = found[0][0]
        pk = ['./' + d + '/...' for mm, d in found if mm == m]
        go_cell(subj, kind, m, pk)
        if rows and rows[-1][0] == subj and rows[-1][1] == kind and rows[-1][2] == 'gap':
            tg = {'integration': 'integration', 'e2e': 'e2e', 'security': 'security', 'stress-chaos': 'stress', 'perf-load': 'benchmark'}.get(kind)
            if tg:
                rows.pop()
                go_cell(subj, kind, m, pk, tags=tg)


# ---- umbrella "root" cells + the T053 extra kinds -------------------------------------------------
# (kind, argv, cwd-relative-to-ROOT, count regex list, tool-needed). cases = sum of the FIRST matching
# regex's integer captured from the command's own output. A designed-red gate (rc 1) still counts: the
# kind is applied and executed cases; the rc is in the evidence. rc 2 / zero cases never becomes check.
ROOT_CELLS = [
    ('integration', ['bash', 'scripts/verify-governance-cascade.sh'], r'(\d+) PASS'),
    ('contract', ['bash', 'scripts/verify-manifest-pins.sh'], r'(\d+) MATCH'),
    ('determinism', ['bash', 'scripts/zero-gap-determinism-modules.sh', '--runs', '2'], r'COUNT:^PASS '),
    ('claim-ledger', ['bash', 'scripts/verify-claim-ledger.sh'], r'(\d+) (?:PASS|rows?|claims?)'),
    ('gate-paired-mutation', ['bash', 'scripts/verify-claim-ledger.sh', '--prove-failure'], r'(\d+) (?:passed|mutations?|caught|assertions)'),
    ('export-validation', ['bash', '_tests/export/self-validate.sh'], r'(\d+) (?:PASS|passed)'),
    ('host-capability', ['bash', 'scripts/hostdeps.sh'], r'(\d+) (?:PASS|present|OK|ok|probed|tools?)'),
    ('provider-ci', ['bash', 'scripts/verify-provider-ci.sh'], r'(\d+) (?:CONFIRMED|repositories|no-trigger)'),
    ('umbrella-mutation', ['bash', 'scripts/prove-umbrella-mutants.sh', '--set', 'mutation'], r'(\d+) killed'),
    ('fuzz', ['bash', 'scripts/prove-umbrella-mutants.sh', '--set', 'fuzz'], r'(\d+) killed'),
    ('vsc375-runtime-probe', ['bash', 'docs/zero-gap/checks/VSC-375.probe.sh'], r'COUNT:^OK '),
    ('manual-qa-readiness', ['bash', 'scripts/zero-gap-qa-readiness.sh'], r'COUNT:^\s*(?:PASS|OK)\b'),
    ('content-boundary', ['bash', 'scripts/verify-content-boundary.sh'], r'LEAK\W+(\d+)|(\d+) enumerated'),
]
# Playwright-backed kinds: one real preflight run decides whether any of them CAN run on this host.
PW_KINDS = ['e2e', 'accessibility', 'perf-load', 'seo-i18n-completeness', 'link-integrity', 'visual-diff']


def measure_root():
    only = a.only
    for kind, argv, rx in ROOT_CELLS:
        if only and only not in ('root', 'root:' + kind):
            continue
        rc, out, dt = run(argv, ROOT, max(a.timeout, 600) if kind == 'content-boundary' else a.timeout)
        cases = 0
        failed = gate_failed(rc, out)   # best-effort; rc carries red regardless (see gate_failed)
        if rx.startswith('COUNT:'):
            cases = len(re.findall(rx[6:], out, re.M))
        else:
            m = re.search(rx, out)
            if m:
                cases = int([g for g in m.groups() if g][0])
        if rc in (124, 137):
            record('root', kind, 'could-not-run:timeout', 0, rc, ' '.join(argv), out)
        elif rc == 127 or rc == 2:
            record('root', kind, 'could-not-run:%s' % os.path.basename(argv[1]), 0, rc, ' '.join(argv), out, 'rc 2 is never a pass')
        elif cases > 0:
            record('root', kind, 'check', cases, rc, ' '.join(argv), out, 'seconds=%.1f failed=%d (parsed from the gate output; rc is authoritative)' % (dt, failed), failed=failed)
        else:
            record('root', kind, 'gap', 0, rc, ' '.join(argv), out, 'executed, zero cases parsed')
    if not only or only.startswith('root'):
        rc, out, dt = run(['node', '_tests/preflight.js'], ROOT, 180)
        blocked = re.findall(r'(?:BLOCKED|MISSING|missing)[^\n]*', out)[:3]
        for kind in PW_KINDS:
            if only and only not in ('root', 'root:' + kind):
                continue
            if rc == 0:
                record('root', kind, 'gap', 0, rc, 'node _tests/preflight.js (READY; suite not run by measurer)', out, 'preflight READY but the Playwright suite is too heavy for this measurer')
            else:
                record('root', kind, 'could-not-run:playwright-preflight', 0, rc, 'node _tests/preflight.js', out, 'preflight rc=%s blockers=%s' % (rc, blocked))


def measure_fuzz():
    subj = 'submodules/qa'
    if a.only and a.only not in (subj, subj + ':fuzz'):
        return
    mods = gomods(subj)
    if not mods:
        return
    cmd = ['go', 'test', '-count=1', '-json', '-run', '^Fuzz', './...']
    rc, out, dt = run(cmd, mods[0], a.timeout)
    p, f, s, bf = go_json_counts(out)
    if bf and p + f == 0: record(subj, 'fuzz', 'could-not-run:go-build', 0, rc, ' '.join(cmd), out)
    elif p + f > 0: record(subj, 'fuzz', 'check', p + f, rc, ' '.join(cmd), out, 'seed-corpus execution; passed=%d failed=%d' % (p, f), failed=f)
    else: record(subj, 'fuzz', 'gap', 0, rc, ' '.join(cmd), out)


def main():
    subs = ['submodules/challenges', 'submodules/containers', 'submodules/curriculum-kit', 'submodules/doc_processor',
            'submodules/llm_orchestrator', 'submodules/llm_provider', 'submodules/LLMProvider', 'submodules/llms_verifier',
            'submodules/passage', 'submodules/qa', 'submodules/RAG', 'submodules/security', 'submodules/verdict',
            'submodules/vision_engine', 'ai_interviewing', 'monetization', 'workshop', 'design-toolkit', 'milosvasic.ru', 'vasic.digital']
    for s in subs:
        if a.only and not a.only.startswith(s):
            continue
        if not os.path.isdir(os.path.join(ROOT, s)):
            continue
        print('== %s' % s, flush=True)
        measure_module(s)
    measure_fuzz()
    measure_root()
    # merge with prior rows when --only is used
    prior = []
    if a.only and os.path.isfile(OUT):
        keep = set((r[0], r[1]) for r in rows)
        for l in open(OUT).read().splitlines()[1:]:
            f = l.split('\t')
            if len(f) == 8 and (f[0], f[1]) not in keep:
                prior.append(tuple(f))
    allrows = sorted(prior + rows)
    with open(OUT, 'w') as fh:
        fh.write('subject\tkind\tstatus\tcases\tfailed\trc\tevidence\tcmd\n')
        for r in allrows:
            fh.write('\t'.join(x.replace('\t', ' ').replace('\n', ' ') for x in r) + '\n')
    print('wrote %s (%d rows)' % (OUT, len(allrows)))


if __name__ == '__main__':
    main()
