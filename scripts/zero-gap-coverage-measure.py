#!/usr/bin/env python3
"""zero-gap-coverage-measure.py - REAL-RUN measurer for the coverage map (feature 010, task T053).

WHAT IT DOES
  For each (subject x test kind) cell it can map to a cheap, bounded, offline invocation, it RUNS that
  invocation and records what executed: the command, the exit code, passed/failed/skipped case counts,
  and a captured evidence file. Output (both tracked, both regenerated by this script only):
    docs/zero-gap/coverage-measured.tsv        subject kind status cases failed rc evidence cmd head tree evsha dirty
                                               (failed and rc are the REAL worst values, never hard-coded;
                                               head = `git rev-parse HEAD` at measurement, tree = sha256 of
                                               head + `git status --porcelain`, i.e. the measured tree state;
                                               evsha = sha256 of the evidence file's SEALED region = everything after
                                               line 1, so a replaced body or an edited ts/limit/dirty line no longer
                                               matches; dirty = 1 when `git status --porcelain` was non-empty at the
                                               start of the run, 0 when clean, `?` for legacy rows sealed after the
                                               fact by --seal-legacy)
    docs/zero-gap/coverage-evidence/*.txt      one captured-output excerpt per measured cell
  scripts/zero-gap-coverage.sh (T052 generator) CONSUMES coverage-measured.tsv: it re-validates every
  row (evidence file exists, cases > 0 for `check`) through its own decide_status() zero-case rule, so
  status is never hand-written into coverage.tsv.

STATUS RULES (FR-010/FR-011)
  check              invocation ran, compiled, executed >= 1 case AND failed == 0 AND rc == 0.
  check-red          invocation executed >= 1 case but a case failed or rc != 0: the kind is APPLIED but
                     not PROVEN, so it is NOT coverage (FR-010/FR-011/SC-005). The generator may upgrade
                     it to `designed-red` only for a gate declared in docs/zero-gap/designed-red.tsv whose
                     declared rc equals the measured rc; the measurer never decides that.
  gap                invocation ran and executed 0 cases, or the kind has no invocation on this subject.
  could-not-run:<t>  the tool/dependency needed is absent or the build failed (never a pass).
                     A Go build failure is `could-not-run:go-build:<cause>` (cause = goproxy-off | missing-replace-dir,
                     joined by `+`) ONLY when the cause of EVERY unbuilt package is environmental (GOPROXY=off for a
                     module that is not in the offline cache; a missing sibling checkout behind a `replace` directive)
                     AND nothing real is red. The cause is decided PER unbuilt package from the build errors that belong
                     to it and is written beside the package in the evidence (`pkg [goproxy-off]`, or `pkg [DEFECT:...]`).
                     A compile error, a typo'd import ("is not in std"), an incomplete go.sum / go.mod ("missing go.sum
                     entry", "no required module provides package"), a package-level failure (panic, TestMain exit,
                     init panic), a failed test, or an rc that nothing explains is a CODE or REPO defect: the cell is
                     `check-red` EVEN WITH ZERO CASES (rc != 0 recorded; the generator keeps it red, not gap) and the
                     evidence lists both the failing tests and the unbuilt packages. Genuine failures are never relabelled.
  n/a:<reason>       declared not applicable with a measured reason (e.g. no UI surface => accessibility).

SAFETY
  Heavy jobs run ONE AT A TIME under `systemd-run --user --scope -p MemoryMax=8G` when available,
  GOPROXY=off, GOFLAGS=-mod=mod is NOT used (read-only module cache). Never touches live services:
  go test is run only on test directories; nothing is started by this script except what the tests
  themselves start in-process.

Usage:  zero-gap-coverage-measure.py [--only SUBJECT[:KIND]] [--timeout SEC] [--root DIR]
"""
