# Playwright-backed kinds: one real preflight run decides whether any of them CAN run on this host.
PW_KINDS = ['e2e', 'accessibility', 'perf-load', 'seo-i18n-completeness', 'link-integrity', 'visual-diff']


def measure_root():
    only = a.only
    for kind, argv, rx in ROOT_CELLS:
        if only and only not in ('root', 'root:' + kind):
            continue
        # explicit, documented limits (F4): the fleet-wide scanning gate gets --gate-timeout (default 600), every
        # other gate gets --timeout (default 240); the limit used is recorded in the evidence (limit=) either way.
        limit = a.gate_timeout if kind == 'content-boundary' else a.timeout
        rc, out, dt = run(argv, ROOT, limit)
        cases = 0
        failed = gate_failed(rc, out)   # best-effort; rc carries red regardless (see gate_failed)
        if rx.startswith('COUNT:'):
            cases = len(re.findall(rx[6:], out, re.M))
        else:
            m = re.search(rx, out)
            if m:
                cases = int([g for g in m.groups() if g][0])
        shown = ' '.join(argv)
        if rc in (124, 137):
            record('root', kind, 'could-not-run:timeout', 0, rc, shown, out,
                   'timed out: limit %ss (%s)' % (limit, '--gate-timeout' if kind == 'content-boundary' else '--timeout'), limit=limit)
        elif rc == 127 or rc == 2:
            record('root', kind, 'could-not-run:%s' % os.path.basename(argv[1]), 0, rc, shown, out, 'rc 2 is never a pass', limit=limit)
        elif cases > 0:
            ids = gate_fail_ids(rc, out)
            record('root', kind, 'check', cases, rc, shown, out,
                   'seconds=%.1f failed=%d (parsed from the gate output; rc is authoritative)' % (dt, failed) + ('\n' + ids if ids else ''),
                   failed=failed, limit=limit)
        else:
            record('root', kind, 'gap', 0, rc, shown, out, 'executed, zero cases parsed', limit=limit)
    if not only or only.startswith('root'):
        rc, out, dt = run(['node', '_tests/preflight.js'], ROOT, 180)
        blocked = re.findall(r'(?:BLOCKED|MISSING|missing)[^\n]*', out)[:3]
        for kind in PW_KINDS:
            if only and only not in ('root', 'root:' + kind):
                continue
            if rc == 0:
                record('root', kind, 'gap', 0, rc, 'node _tests/preflight.js (READY; suite not run by measurer)', out, 'preflight READY but the Playwright suite is too heavy for this measurer', limit=180)
            else:
                record('root', kind, 'could-not-run:playwright-preflight', 0, rc, 'node _tests/preflight.js', out, 'preflight rc=%s blockers=%s' % (rc, blocked), limit=180)


def measure_fuzz():
    subj = 'submodules/qa'
    if a.only and a.only not in (subj, subj + ':fuzz'):
        return
    mods = gomods(subj)
    if not mods:
        return
    cmd = ['go', 'test', '-count=1', '-json', '-run', '^Fuzz', './...']
    rc, out, dt = run(cmd, mods[0], a.timeout)
    an = go_analyze(out, False, rc)
    emit_go(subj, 'fuzz', [an], ' '.join(cmd), out, a.timeout, 'seed-corpus execution; passed=%d failed=%d' % (an['p'], an['f']))


def prior_binding(ev):
    """(head, tree) as recorded in an existing evidence file's own header; ('-', '-') when there is none."""
    try:
        h = open(os.path.join(ROOT, ev)).read().splitlines()[1]
        kv = dict(x.split('=', 1) for x in h.split() if '=' in x)
        return kv.get('head', '-'), kv.get('tree', '-')
    except Exception:
        return '-', '-'


