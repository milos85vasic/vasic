    # F3: failing names
    many = [jl(Action='fail', Package='m/p%d' % (i % 7), Test='TestF%d' % i) for i in range(620)]
    an = go_analyze('\n'.join(many), rc=1)
    det = go_detail(an)
    chk('F3 620 failing tests: first 500 listed by package+test, 120 omitted and counted', det.count('  m/p') == 500 and 'failing-tests (620; 120 omitted from this list)' in det)
    an62 = go_analyze('\n'.join(jl(Action='fail', Package='ai/x', Test='TestN%d' % i) for i in range(62)), rc=1)
    chk('F3 62 failures are all listable from the evidence block alone', go_detail(an62).count('ai/x :: TestN') == 62)
    gd = gate_fail_ids(1, '== ledger\nrows: 10\nFALSE   [blocker] readme-zero-findings-badge — occurrence says 23\n9 VERIFIED · 1 FALSE · 0 ORPHAN\n❌ CLAIM-VS-REALITY [DEFECT]: 1 claim(s)\n')
    chk('F3 gate: failing case identifiers listed (FALSE row, DEFECT line), summary line not double-listed', 'readme-zero-findings-badge' in gd and 'DEFECT' in gd and '(2' in gd)
    chk('F3 gate: rc 0 lists nothing (golden-bad FAIL lines are not failures)', gate_fail_ids(0, 'FAIL golden-bad arm\n') == '')
    chk('F3 gate: rc 1 with no nameable line says so instead of listing nothing silently', 'none identified' in gate_fail_ids(1, 'all quiet\n'))
    print('measure selftest: %s' % ('ok' if ok else 'FAILED'))
    return ok


