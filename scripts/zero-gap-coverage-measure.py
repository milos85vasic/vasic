def gomods(subj):
    """Own, TRACKED go.mod directories of a subject (never harvested third-party copies, vendor,
    node_modules, upstream-contributions), shortest path first, capped at 6 modules."""
    base = os.path.join(ROOT, subj)
    ls = subprocess.run(['git', '-C', base, 'ls-files', '--', 'go.mod', '**/go.mod'], stdout=subprocess.PIPE).stdout.decode().split('\n')
    skip = ('_harvest/', 'vendor/', 'node_modules/', 'upstream-contributions/', 'output/', '/venv/')
    res = [os.path.join(base, os.path.dirname(l)) for l in ls if l and not any(x in l for x in skip)]
    res = sorted(set(os.path.normpath(r) for r in res), key=lambda r: (len(r), r))
    return res[:6]


