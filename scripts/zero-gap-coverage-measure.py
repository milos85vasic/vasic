def emit_go(subj, kind, ans, shown, out, limit, note):
    """One Go cell from one or more per-module analyses: classify (F2), list failing tests / unbuilt packages (F3),
    record. rc is the WORST module rc."""
    an = merge_analyses(ans)
    rc = an['rc']
    st, cases, failed = classify_go(an, rc)
    detail = go_detail(an)
    extra = note + ('\n' + detail if detail else '')
    if st == 'could-not-run:timeout':
        extra = 'timed out: limit %ss\n%s' % (limit, extra)
    elif st.startswith('could-not-run:go-build'):
        extra = 'environment build failure, not a test failure; cases = passing cases of the packages that did run\n' + extra
    record(subj, kind, st, cases, rc, shown, out, extra, failed=failed, limit=limit)


