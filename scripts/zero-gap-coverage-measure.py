def measure_root():
    only = a.only
    for kind, argv, rx in ROOT_CELLS:
        if only and only not in ('root', 'root:' + kind):
            continue
        # explicit, documented limits (F4): the fleet-wide scanning gate gets --gate-timeout (default 600), every
        # other gate gets --timeout (default 240); the limit used is recorded in the evidence (limit=) either way.
        limit = a.gate_timeout if kind == 'content-boundary' else a.timeout
        rc, out, dt = run(argv, ROOT, limit)
        cases = 0
        failed = gate_failed(rc, out)   # best-effort; rc carries red regardless (see gate_failed)
        if rx.startswith('COUNT:'):
            cases = len(re.findall(rx[6:], out, re.M))
        else:
            m = re.search(rx, out)
            if m:
                cases = int([g for g in m.groups() if g][0])
        shown = ' '.join(argv)
        if rc in (124, 137):
            record('root', kind, 'could-not-run:timeout', 0, rc, shown, out,
                   'timed out: limit %ss (%s)' % (limit, '--gate-timeout' if kind == 'content-boundary' else '--timeout'), limit=limit)
        elif rc == 127 or rc == 2:
            record('root', kind, 'could-not-run:%s' % os.path.basename(argv[1]), 0, rc, shown, out, 'rc 2 is never a pass', limit=limit)
        elif cases > 0:
            ids = gate_fail_ids(rc, out)
            record('root', kind, 'check', cases, rc, shown, out,
                   'seconds=%.1f failed=%d (parsed from the gate output; rc is authoritative)' % (dt, failed) + ('\n' + ids if ids else ''),
                   failed=failed, limit=limit)
        else:
            record('root', kind, 'gap', 0, rc, shown, out, 'executed, zero cases parsed', limit=limit)
    if not only or only.startswith('root'):
        rc, out, dt = run(['node', '_tests/preflight.js'], ROOT, 180)
        blocked = re.findall(r'(?:BLOCKED|MISSING|missing)[^\n]*', out)[:3]
        for kind in PW_KINDS:
            if only and only not in ('root', 'root:' + kind):
                continue
            if rc == 0:
                record('root', kind, 'gap', 0, rc, 'node _tests/preflight.js (READY; suite not run by measurer)', out, 'preflight READY but the Playwright suite is too heavy for this measurer', limit=180)
            else:
                record('root', kind, 'could-not-run:playwright-preflight', 0, rc, 'node _tests/preflight.js', out, 'preflight rc=%s blockers=%s' % (rc, blocked), limit=180)


def measure_fuzz():
    subj = 'submodules/qa'
    if a.only and a.only not in (subj, subj + ':fuzz'):
        return
    mods = gomods(subj)
    if not mods:
        return
    cmd = ['go', 'test', '-count=1', '-json', '-run', '^Fuzz', './...']
    rc, out, dt = run(cmd, mods[0], a.timeout)
    an = go_analyze(out, False, rc)
    emit_go(subj, 'fuzz', [an], ' '.join(cmd), out, a.timeout, 'seed-corpus execution; passed=%d failed=%d' % (an['p'], an['f']))


def seal_legacy():
    """One-off migration for rows measured BEFORE round 3 (no `evsha`, dirty state unknown). Runs NOTHING. For every row
    with an evidence file and no evsha: strip the absolute repo path from the file (reported), then record the sha256 of
    the evidence file's sealed region as it stands NOW and mark dirty `?` (unknown). HONEST LIMIT: this seals the bytes
    present at sealing time; it cannot prove they were not altered between measurement and sealing - the git history of
    the committed TSV and evidence files is the only record of that. Rows measured by this measurer from round 3 on carry
    evsha from the moment of measurement and are never touched here."""
    if not os.path.isfile(OUT):
        print('no %s' % OUT); return 2
    lines = open(OUT).read().splitlines()
    out = [TSV_HEADER.rstrip('\n')]; sealed = scrubbed = skipped = 0
    for l in lines[1:]:
        f = l.split('\t')
        if len(f) == 10:
            f += ['-', '?']
        if len(f) != 12:
            print('malformed row kept as-is: %s' % l[:80]); out.append(l); continue
        if f[6] and f[10] in ('-', ''):
            p = os.path.join(ROOT, f[6])
            if not os.path.isfile(p):
                print('evidence file absent, row left unsealed: %s %s' % (f[0], f[1])); skipped += 1
            else:
                t = open(p).read(); t2 = strip_root(t, ROOT)
                if t2 != t:
                    open(p, 'w').write(t2); scrubbed += 1
                f[10] = body_sha(t2); f[11] = '?'; sealed += 1
        f[7] = strip_root(f[7], ROOT)
        out.append('\t'.join(f))
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(out) + '\n')
    print('seal-legacy: sealed %d evidence file(s) (dirty=? unknown), %d had the repo path stripped, %d left unsealed' % (sealed, scrubbed, skipped))
    return 0


def prior_binding(ev):
    """(head, tree) as recorded in an existing evidence file's own header; ('-', '-') when there is none."""
    try:
        h = open(os.path.join(ROOT, ev)).read().splitlines()[1]
        kv = dict(x.split('=', 1) for x in h.split() if '=' in x)
        return kv.get('head', '-'), kv.get('tree', '-')
    except Exception:
        return '-', '-'


def main():
    binding()   # snapshot head/tree/dirty BEFORE this run writes anything
    subs = ['submodules/challenges', 'submodules/containers', 'submodules/curriculum-kit', 'submodules/doc_processor',
            'submodules/llm_orchestrator', 'submodules/llm_provider', 'submodules/LLMProvider', 'submodules/llms_verifier',
            'submodules/passage', 'submodules/qa', 'submodules/RAG', 'submodules/security', 'submodules/verdict',
            'submodules/vision_engine', 'ai_interviewing', 'monetization', 'workshop', 'design-toolkit', 'milosvasic.ru', 'vasic.digital']
    for s in subs:
        if a.only and not a.only.startswith(s):
            continue
        if not os.path.isdir(os.path.join(ROOT, s)):
            continue
        print('== %s' % s, flush=True)
        measure_module(s)
    measure_fuzz()
    measure_root()
    # merge with prior rows when --only is used
    prior = []
    if a.only and os.path.isfile(OUT):
        keep = set((r[0], r[1]) for r in rows)
        for l in open(OUT).read().splitlines()[1:]:
            f = l.split('\t')
            if len(f) == 8:   # pre-round-2 row: carry the head/tree it was MEASURED at (from its own evidence header)
                f += list(prior_binding(f[6]))
            if len(f) == 10:  # pre-round-3 row: no sealed evidence body yet (run --seal-legacy), dirty state unknown
                f += ['-', '?']
            if len(f) == 12 and (f[0], f[1]) not in keep:
                prior.append(tuple(f))
    allrows = sorted(prior + rows)
    with open(OUT, 'w') as fh:
        fh.write(TSV_HEADER)
        for r in allrows:
            fh.write('\t'.join(x.replace('\t', ' ').replace('\n', ' ') for x in r) + '\n')
    print('wrote %s (%d rows)' % (OUT, len(allrows)))


if __name__ == '__main__':
    if a.seal_legacy:
        sys.exit(seal_legacy())
    main()
