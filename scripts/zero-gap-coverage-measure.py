def classify(cases, failed, rc):
    """FR-010/FR-011: covered only when cases>0 AND failed==0 AND rc==0; cases>0 otherwise is red."""
    if cases <= 0:
        return 'gap'
    return 'check' if (failed == 0 and rc == 0) else 'check-red'


def aggregate_unit(results):
    """results: one dict per module that ran tests (rc, p, f, s). Returns the REAL totals: summed
    passed/failed/skipped and the WORST (largest) exit code - never a hard-coded 0."""
    return {'passed': sum(r['p'] for r in results), 'failed': sum(r['f'] for r in results),
            'skipped': sum(r['s'] for r in results), 'rc': max([r['rc'] for r in results] or [0])}


# ---- Go output analysis (T061 round 2, findings F2/F3) -------------------------------------------
# Causes that belong to the MEASURER'S ENVIRONMENT (offline module cache, missing sibling checkouts),
# not to the code under test. Order is the order they are reported in.
ENV_CAUSES = [
    ('goproxy-off', re.compile(r'module lookup disabled by GOPROXY=off|GOPROXY list is not the empty string')),
    ('missing-replace-dir', re.compile(r'replacement directory .* does not exist')),
    ('missing-module', re.compile(r'no required module provides package|cannot find module providing package|cannot find module|'
                                  r'missing go\.sum entry|no matching versions for query|is not in std')),
]
COMPILE_ERR = re.compile(r'\.go:\d+:\d+:')
LIST_CAP = 500   # names listed per evidence file; the rest is counted, never silently dropped


def env_causes_of(line):
    return [lab for lab, rx in ENV_CAUSES if rx.search(line)]


def go_analyze(out, bench_mode=False, rc=0):
    """Parse `go test -json` output (plus the non-JSON lines the go tool itself prints) into one record:
    p/f/s case counts; fails = [(package, test)] of every failed test; unbuilt = packages that did not build
    (FailedBuild / [build failed] / [setup failed]); causes = ENV causes seen in the build errors;
    compile_err = a build error that is NOT an env cause (a real defect in the code under test);
    pkg_fail = packages that failed with no failed test and no build failure (panic, timeout, TestMain exit);
    unexplained = rc != 0 (not a timeout) with no failed test and no build signal at all."""
    p = f = s = 0
    fails = []; err_lines = []; pkgfail = {}; setup_flag = set(); failed_pkgs = set(); legacy_bf = False
    for line in out.splitlines():
        if line.startswith('{'):
            try:
                ev = json.loads(line)
            except Exception:
                continue
            act = ev.get('Action'); pkg = ev.get('Package') or ''
            if ev.get('Test'):
                if act == 'pass': p += 1
                elif act == 'fail':
                    f += 1; fails.append((pkg, ev['Test'])); failed_pkgs.add(pkg)
                elif act == 'skip': s += 1
                continue
            if act == 'build-output':
                err_lines.append(ev.get('Output') or '')
            elif act == 'fail' and pkg:
                pkgfail[pkg] = ev.get('FailedBuild') or ''
                if ev.get('FailedBuild'): legacy_bf = True
            elif act == 'output' and pkg:
                o = ev.get('Output') or ''
                if '[build failed]' in o or '[setup failed]' in o:
                    setup_flag.add(pkg); err_lines.append(o)
            if act == 'fail' and 'build failed' in (ev.get('Output') or ''):
                legacy_bf = True
        elif line.strip():
            err_lines.append(line)
            if 'build failed' in line or 'cannot find module' in line or 'no required module' in line \
                    or 'GOPROXY list is not the empty string' in line or 'missing go.sum' in line:
                legacy_bf = True
    causes = set(); compile_err = False
    for l in err_lines:
        c = env_causes_of(l)
        causes.update(c)
        if not c and COMPILE_ERR.search(l):
            compile_err = True
    if 'module lookup disabled' in out or '"Action":"build-fail"' in out or 'FailedBuild' in out:
        legacy_bf = True
    unbuilt = sorted(pk for pk, fb in pkgfail.items() if fb or pk in setup_flag) + sorted(setup_flag - set(pkgfail))
    unbuilt = sorted(set(unbuilt))
    pkg_fail = sorted(pk for pk, fb in pkgfail.items() if not fb and pk not in setup_flag and pk not in failed_pkgs)
    if bench_mode:
        p = max(p, len(re.findall(r'ns/op', out)))
    explained = f > 0 or bool(pkg_fail) or bool(unbuilt) or bool(causes) or compile_err
    unexplained = (rc not in (0, 124, 137)) and not explained
    return {'p': p, 'f': f, 's': s, 'fails': fails, 'unbuilt': unbuilt, 'causes': sorted(causes),
            'compile_err': compile_err, 'pkg_fail': pkg_fail, 'bf': legacy_bf or bool(unbuilt) or bool(causes),
            'unexplained': unexplained, 'rc': rc}


def merge_analyses(ans):
    m = {'p': 0, 'f': 0, 's': 0, 'fails': [], 'unbuilt': [], 'causes': [], 'compile_err': False, 'pkg_fail': [],
         'bf': False, 'unexplained': False, 'rc': 0}
    for x in ans:
        for k in ('p', 'f', 's'):
            m[k] += x[k]
        m['fails'] += x['fails']; m['unbuilt'] += x['unbuilt']; m['pkg_fail'] += x['pkg_fail']
        m['causes'] = sorted(set(m['causes']) | set(x['causes']))
        for k in ('compile_err', 'bf', 'unexplained'):
            m[k] = m[k] or x[k]
        m['rc'] = max(m['rc'], x['rc'])
    m['unbuilt'] = sorted(set(m['unbuilt'])); m['pkg_fail'] = sorted(set(m['pkg_fail']))
    return m


def classify_go(an, rc):
    """The status of a Go cell from its merged analysis (F2). Returns (status, cases, failed).
      cases == 0                                  -> gap, or could-not-run:go-build:<cause> when a build failed
      env-only build failures (rc != 0, nothing real red) -> could-not-run:go-build:<cause>
      anything real (failed tests, package failure, compile error, unexplained rc) -> check / check-red"""
    cases = an['p'] + an['f']
    if rc in (124, 137):   # the limit fired: a timeout is not a verdict on the code, unless a real failure was already seen
        if an['f'] > 0 or an['pkg_fail'] or an['compile_err']:
            return classify(cases, an['f'], rc), cases, an['f']
        return 'could-not-run:timeout', cases, 0
    cause = '+'.join(an['causes']) or ('compile-error' if an['compile_err'] else 'unknown')
    real_red = an['f'] > 0 or bool(an['pkg_fail']) or an['compile_err'] or an['unexplained']
    if cases == 0:
        return (('could-not-run:go-build:' + cause) if an['bf'] else 'gap'), 0, 0
    if rc == 0 or real_red:
        return classify(cases, an['f'], rc), cases, an['f']
    return 'could-not-run:go-build:' + cause, cases, 0


def cap_list(items, cap=LIST_CAP):
    items = list(items)
    shown = items[:cap]
    return shown, max(0, len(items) - cap)


def go_detail(an):
    """Evidence block (F3): every failing test and every unbuilt package, by name, capped at LIST_CAP each with
    the omitted count stated. Written into the evidence header region so it survives the body truncation."""
    lines = []
    if an['causes']:
        lines.append('build-failure-causes=%s' % '+'.join(an['causes']))
    if an['compile_err']:
        lines.append('compile-error=yes (a build error that is not an environment cause)')
    if an['unbuilt']:
        sh, om = cap_list(an['unbuilt'])
        lines.append('unbuilt-packages (%d%s):' % (len(an['unbuilt']), '; %d omitted from this list' % om if om else ''))
        lines += ['  ' + x for x in sh]
    if an['pkg_fail']:
        sh, om = cap_list(an['pkg_fail'])
        lines.append('package-level-failures (%d%s):' % (len(an['pkg_fail']), '; %d omitted from this list' % om if om else ''))
        lines += ['  ' + x for x in sh]
    if an['fails']:
        sh, om = cap_list('%s :: %s' % (pk, t) for pk, t in an['fails'])
        lines.append('failing-tests (%d%s):' % (len(an['fails']), '; %d omitted from this list' % om if om else ''))
        lines += ['  ' + x for x in sh]
    return '\n'.join(lines)


GATE_FAIL = re.compile(r'(?:^\s*[\[(]?(?:FALSE|FAIL|FAILED|DRIFT|DEFECT|CONFIRMED|ORPHAN|MALFORMED|NOT OK|not ok)\b)|❌|✗|✘|'
                       r'\b(?:CONFIRMED|FALSE|FAIL|FAILED|DRIFT|DEFECT)\s*$')


def gate_fail_ids(rc, out):
    """Failing case identifiers of a root GATE script (F3), best effort: only when rc != 0 (a gate that exits 0
    prints FAIL lines for its golden-bad arms, which are not failures). Returns the evidence block."""
    if rc == 0:
        return ''
    ids = [re.sub(r'\s+', ' ', l.strip())[:200] for l in out.splitlines() if GATE_FAIL.search(l)]
    if not ids:
        return 'failing-cases: none identified by name in the gate output (rc %s is authoritative)' % rc
    sh, om = cap_list(ids)
    return 'failing-cases (%d%s; best effort from the gate output, rc is authoritative):\n%s' % (
        len(ids), '; %d omitted from this list' % om if om else '', '\n'.join('  ' + x for x in sh))


def go_json_counts(out, bench_mode=False):
    an = go_analyze(out, bench_mode)
    return an['p'], an['f'], an['s'], an['bf']


_BIND = {}


def binding():
    """head= (git HEAD), tree= (sha256 of HEAD + `git status --porcelain` = the exact tree state that was
    measured), ts= (UTC). head/tree are computed once per run; ts per record."""
    if 'head' not in _BIND:
        def g(*args):
            return subprocess.run(['git', '-C', ROOT] + list(args), stdout=subprocess.PIPE, stderr=subprocess.DEVNULL).stdout.decode()
        head = g('rev-parse', 'HEAD').strip() or '0' * 40
        _BIND['head'] = head
        _BIND['tree'] = hashlib.sha256((head + '\n' + g('status', '--porcelain=v1')).encode()).hexdigest()
    return _BIND['head'], _BIND['tree'], datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')


def evidence_header(subj, kind, status, cases, failed, rc, cmd, extra, head, tree, ts, limit='-'):
    return ('subject=%s kind=%s status=%s cases=%s failed=%s rc=%s\nhead=%s tree=%s ts=%s limit=%s\ncmd=%s\n%s\n---\n'
            % (subj, kind, status, cases, failed, rc, head, tree, ts, limit, cmd, extra))


def gate_failed(rc, out):
    """Failed-case count of a root GATE script, best effort. A gate that exits 0 has no failed result of its
    own: FAIL/failed lines in its output belong to its golden-bad (must-detect) arms and are NOT failures.
    Only a non-zero rc makes the parsed count meaningful; rc itself stays authoritative either way."""
    if rc == 0:
        return 0
    return max([int(x) for x in re.findall(r'(\d+) (?:FAIL(?:ED)?|DRIFT|DEFECT|failed)\b', out)] or [0])


def jl(**kw):
    return json.dumps(kw)


def selftest():
    ok = True

    def chk(name, cond):
        nonlocal ok
        print('  %s %s' % ('PASS' if cond else 'FAIL', name))
        ok = ok and cond
    agg = aggregate_unit([{'rc': 0, 'p': 10, 'f': 0, 's': 1}, {'rc': 1, 'p': 57, 'f': 62, 's': 0}])
