def classify(cases, failed, rc):
    """FR-010/FR-011: covered only when cases>0 AND failed==0 AND rc==0; cases>0 otherwise is red."""
    if cases <= 0:
        return 'gap'
    return 'check' if (failed == 0 and rc == 0) else 'check-red'


def aggregate_unit(results):
    """results: one dict per module that ran tests (rc, p, f, s). Returns the REAL totals: summed
    passed/failed/skipped and the WORST (largest) exit code - never a hard-coded 0."""
    return {'passed': sum(r['p'] for r in results), 'failed': sum(r['f'] for r in results),
            'skipped': sum(r['s'] for r in results), 'rc': max([r['rc'] for r in results] or [0])}


# ---- Go output analysis (T061 round 2 F2/F3, round 3 per-package causes) -------------------------
# Causes that belong to the MEASURER'S ENVIRONMENT (offline module cache, missing sibling checkouts), not to the code
# under test. ONLY these two are environmental. Round 3 removed `missing-module`: its patterns ("is not in std",
# "missing go.sum entry", "no required module provides package") describe CODE or REPO defects (a typo'd import, an
# incomplete tracked go.sum / go.mod), which must stay check-red. Order is the order they are reported in.
ENV_CAUSES = [
    ('goproxy-off', re.compile(r'module lookup disabled by GOPROXY=off|GOPROXY list is not the empty string')),
    ('missing-replace-dir', re.compile(r'replacement directory .* does not exist')),
]
ENV_LABELS = tuple(lab for lab, _ in ENV_CAUSES)
COMPILE_ERR = re.compile(r'\.go:\d+:\d+:')
LIST_CAP = 500   # names listed per evidence file; the rest is counted, never silently dropped


def env_causes_of(line):
    return [lab for lab, rx in ENV_CAUSES if rx.search(line)]


def pkg_cause(lines):
    """The cause of ONE unbuilt package from the error lines attributable to it. Returns (kind, label):
      ('env', 'goproxy-off+...')    every explained error is environmental and at least one was seen
      ('defect', 'compile-error')   a `file.go:L:C:` error that is NOT an environment cause is present (even beside env lines)
      ('defect', 'unknown')         no attributable error line at all: nothing proves the environment, so it is not claimed"""
    env = set(); compile_defect = False
    for l in lines:
        c = env_causes_of(l)
        if c:
            env.update(c)
        elif COMPILE_ERR.search(l):
            compile_defect = True
    if compile_defect:
        return 'defect', 'compile-error'
    if env:
        return 'env', '+'.join(lab for lab in ENV_LABELS if lab in env)
    return 'defect', 'unknown'


def go_analyze(out, bench_mode=False, rc=0):
    """Parse `go test -json` output (plus the non-JSON lines the go tool itself prints) into one record:
    p/f/s case counts; fails = [(package, test)]; unbuilt = packages that did not build (FailedBuild / [build failed] /
    [setup failed]); pkg_cause = {package: (kind, label)} decided PER unbuilt package from the build errors attributable
    to it; causes = environment labels of the env-only packages; defects = unbuilt packages whose cause is NOT
    environmental; compile_err = a defect package or a global line with a real compile error; pkg_fail = packages that
    failed with no failed test and no build failure (panic, timeout, TestMain exit); counts = {package: [p, f, s]};
    unexplained = rc != 0 (not a timeout) with no failed test, no package failure and no build signal at all."""
    p = f = s = 0
    fails = []; pkgfail = {}; setup_flag = set(); failed_pkgs = set(); legacy_bf = False
    bo = {}; pkg_out = {}; glob = []; counts = {}
    for line in out.splitlines():
        if line.startswith('{'):
            try:
                ev = json.loads(line)
            except Exception:
                continue
            act = ev.get('Action'); pkg = ev.get('Package') or ''
            if ev.get('Test'):
                c = counts.setdefault(pkg, [0, 0, 0])
                if act == 'pass': p += 1; c[0] += 1
                elif act == 'fail':
                    f += 1; c[1] += 1; fails.append((pkg, ev['Test'])); failed_pkgs.add(pkg)
                elif act == 'skip': s += 1; c[2] += 1
                continue
            if act == 'build-output':
                bo.setdefault(ev.get('ImportPath') or '', []).append(ev.get('Output') or '')
            elif act == 'fail' and pkg:
                pkgfail[pkg] = ev.get('FailedBuild') or ''
                if ev.get('FailedBuild'): legacy_bf = True
            elif act == 'output' and pkg:
                o = ev.get('Output') or ''
                pkg_out.setdefault(pkg, []).append(o)
                if '[build failed]' in o or '[setup failed]' in o:
                    setup_flag.add(pkg)
            if act == 'fail' and 'build failed' in (ev.get('Output') or ''):
                legacy_bf = True
        elif line.strip():
            glob.append(line)
            if 'build failed' in line or 'cannot find module' in line or 'no required module' in line \
                    or 'GOPROXY list is not the empty string' in line or 'missing go.sum' in line:
                legacy_bf = True
    if 'module lookup disabled' in out or '"Action":"build-fail"' in out or 'FailedBuild' in out:
        legacy_bf = True
    unbuilt = sorted(set([pk for pk, fb in pkgfail.items() if fb or pk in setup_flag] + list(setup_flag)))
    pkg_fail = sorted(pk for pk, fb in pkgfail.items() if not fb and pk not in setup_flag and pk not in failed_pkgs)
    cause_of = {}
    for pk in unbuilt:
        lines = list(bo.get(pkgfail.get(pk) or '', [])) + list(bo.get(pk, [])) + list(pkg_out.get(pk, []))
        if not any(env_causes_of(l) or COMPILE_ERR.search(l) for l in lines):
            lines = lines + glob   # old go: the build errors are plain non-JSON lines, unattributable to one package
        cause_of[pk] = pkg_cause(lines)
    causes = sorted(set(lab for k, lab in cause_of.values() if k == 'env' for lab in lab.split('+')), key=ENV_LABELS.index)
    defects = [pk for pk in unbuilt if cause_of[pk][0] == 'defect']
    compile_err = any(cause_of[pk][1] == 'compile-error' for pk in defects)
    if not unbuilt:   # no per-package attribution exists: the global (non-JSON) lines decide
        gk, gl = pkg_cause(glob) if glob else ('defect', 'unknown')
        if glob and gk == 'env':
            causes = sorted(set(gl.split('+')), key=ENV_LABELS.index)
        elif gl == 'compile-error':
            compile_err = True
    if bench_mode:
        p = max(p, len(re.findall(r'ns/op', out)))
    explained = f > 0 or bool(pkg_fail) or bool(unbuilt) or bool(causes) or compile_err
    unexplained = (rc not in (0, 124, 137)) and not explained
    pc = {pk: counts[pk] for pk in counts}
    return {'p': p, 'f': f, 's': s, 'fails': fails, 'unbuilt': unbuilt, 'causes': causes, 'pkg_cause': cause_of,
            'defects': defects, 'compile_err': compile_err, 'pkg_fail': pkg_fail, 'counts': pc,
            'bf': legacy_bf or bool(unbuilt) or bool(causes), 'unexplained': unexplained, 'rc': rc}


def merge_analyses(ans):
    m = {'p': 0, 'f': 0, 's': 0, 'fails': [], 'unbuilt': [], 'causes': [], 'pkg_cause': {}, 'defects': [], 'compile_err': False,
         'pkg_fail': [], 'counts': {}, 'bf': False, 'unexplained': False, 'rc': 0}
    for x in ans:
        for k in ('p', 'f', 's'):
            m[k] += x[k]
        m['fails'] += x['fails']; m['unbuilt'] += x['unbuilt']; m['pkg_fail'] += x['pkg_fail']; m['defects'] += x['defects']
        m['causes'] = sorted(set(m['causes']) | set(x['causes']), key=ENV_LABELS.index)
        for pk, c in x['pkg_cause'].items():
            if pk not in m['pkg_cause'] or c[0] == 'defect':   # the same package in two modules: a defect outranks env
                m['pkg_cause'][pk] = c
        for pk, c in x['counts'].items():
            mc = m['counts'].setdefault(pk, [0, 0, 0])
            for i in range(3):
                mc[i] += c[i]
        for k in ('compile_err', 'bf', 'unexplained'):
            m[k] = m[k] or x[k]
        m['rc'] = max(m['rc'], x['rc'])
    m['unbuilt'] = sorted(set(m['unbuilt'])); m['pkg_fail'] = sorted(set(m['pkg_fail'])); m['defects'] = sorted(set(m['defects']))
    return m


def classify_go(an, rc):
    """The status of a Go cell from its merged analysis. Returns (status, cases, failed). DECIDED PER PACKAGE (round 3):
    an environment label is allowed only when EVERY unbuilt package's cause is environmental AND nothing real is red.
      anything real red (failed tests, package failure, a non-environment unbuilt package, compile error, an rc that
      nothing explains) -> check-red, EVEN WITH ZERO CASES (a code defect that stopped every test from running is
      still a defect; the generator keeps check-red with cases 0 and rc != 0 as red, not as gap)
      env-only build failures (rc != 0, nothing real red)  -> could-not-run:go-build:<cause>
      rc 0 -> check / gap by case count"""
    cases = an['p'] + an['f']
    real_red = an['f'] > 0 or bool(an['pkg_fail']) or bool(an['defects']) or an['compile_err'] or an['unexplained']
    if rc in (124, 137):   # the limit fired: a timeout is not a verdict on the code, unless a real failure was already seen
        if an['f'] > 0 or an['pkg_fail'] or an['defects'] or an['compile_err']:
            return ('check-red' if rc else classify(cases, an['f'], rc)), cases, an['f']
        return 'could-not-run:timeout', cases, 0
    if real_red:
        return ('check-red' if rc != 0 else classify(cases, an['f'], rc)), cases, an['f']
    if rc == 0:
        return classify(cases, an['f'], rc), cases, an['f']
    if rc in (125, 127) and not an['bf']:
        return 'could-not-run:exec', cases, 0
    return 'could-not-run:go-build:' + '+'.join(an['causes']), cases, 0


def cap_list(items, cap=LIST_CAP):
    items = list(items)
    shown = items[:cap]
    return shown, max(0, len(items) - cap)


def go_detail(an):
    """Evidence block (F3, round 3): every failing test, every unbuilt package WITH its per-package cause (a package whose
    cause is not environmental is tagged [DEFECT:<cause>]) and the per-package pass/fail/skip counts, each capped at
    LIST_CAP with the omitted count stated. Written into the evidence header region so it survives the body truncation."""
    lines = []
    if an['causes']:
        lines.append('build-failure-causes=%s' % '+'.join(an['causes']))
    if an['compile_err']:
        lines.append('compile-error=yes (a build error that is not an environment cause)')
    if an['unbuilt']:
        sh, om = cap_list(an['unbuilt'])
        lines.append('unbuilt-packages (%d%s):' % (len(an['unbuilt']), '; %d omitted from this list' % om if om else ''))
        for x in sh:
            k, lab = an['pkg_cause'].get(x, ('defect', 'unknown'))
            lines.append('  %s [%s]' % (x, lab if k == 'env' else 'DEFECT:' + lab))
    if an['pkg_fail']:
        sh, om = cap_list(an['pkg_fail'])
        lines.append('package-level-failures (%d%s):' % (len(an['pkg_fail']), '; %d omitted from this list' % om if om else ''))
        lines += ['  ' + x for x in sh]
    if an['fails']:
        sh, om = cap_list('%s :: %s' % (pk, t) for pk, t in an['fails'])
        lines.append('failing-tests (%d%s):' % (len(an['fails']), '; %d omitted from this list' % om if om else ''))
        lines += ['  ' + x for x in sh]
    if an['counts']:
        sh, om = cap_list('%s pass=%d fail=%d skip=%d' % (pk, c[0], c[1], c[2]) for pk, c in sorted(an['counts'].items()))
        lines.append('package-counts (%d packages%s):' % (len(an['counts']), '; %d omitted from this list' % om if om else ''))
        lines += ['  ' + x for x in sh]
    return '\n'.join(lines)


GATE_FAIL = re.compile(r'(?:^\s*[\[(]?(?:FALSE|FAIL|FAILED|DRIFT|DEFECT|CONFIRMED|ORPHAN|MALFORMED|NOT OK|not ok)\b)|❌|✗|✘|'
                       r'\b(?:CONFIRMED|FALSE|FAIL|FAILED|DRIFT|DEFECT)\s*$')


def gate_fail_ids(rc, out):
    """Failing case identifiers of a root GATE script (F3), best effort: only when rc != 0 (a gate that exits 0
    prints FAIL lines for its golden-bad arms, which are not failures). Returns the evidence block."""
    if rc == 0:
        return ''
    ids = [re.sub(r'\s+', ' ', l.strip())[:200] for l in out.splitlines() if GATE_FAIL.search(l)]
    if not ids:
        return 'failing-cases: none identified by name in the gate output (rc %s is authoritative)' % rc
    sh, om = cap_list(ids)
    return 'failing-cases (%d%s; best effort from the gate output, rc is authoritative):\n%s' % (
        len(ids), '; %d omitted from this list' % om if om else '', '\n'.join('  ' + x for x in sh))


def go_json_counts(out, bench_mode=False):
    an = go_analyze(out, bench_mode)
    return an['p'], an['f'], an['s'], an['bf']


_BIND = {}


def dirty_state(porcelain):
    """From `git status --porcelain=v1` output: dirty (0|1), a short stable digest of the sorted entries, and the sorted
    paths. The digest lets two measurements be recognised as taken on the same dirty tree without storing the tree."""
    ents = [l for l in porcelain.splitlines() if l.strip()]
    paths = sorted(set(l[3:].strip() for l in ents))
    return {'dirty': 1 if ents else 0, 'digest': hashlib.sha256('\n'.join(sorted(ents)).encode()).hexdigest()[:12] if ents else '-',
            'paths': paths}


def binding():
    """head= (git HEAD), tree= (sha256 of HEAD + `git status --porcelain` = the exact tree state that was measured),
    dirty= (the same porcelain reduced to dirty/clean + digest), ts= (UTC). Computed ONCE per run, at the start of main()
    (before this run writes anything); ts per record."""
    if 'head' not in _BIND:
        def g(*args):
            return subprocess.run(['git', '-C', ROOT] + list(args), stdout=subprocess.PIPE, stderr=subprocess.DEVNULL).stdout.decode()
        head = g('rev-parse', 'HEAD').strip() or '0' * 40
        por = g('status', '--porcelain=v1')
        _BIND['head'] = head
        _BIND['tree'] = hashlib.sha256((head + '\n' + por).encode()).hexdigest()
        _BIND['dirty'] = dirty_state(por)
    return _BIND['head'], _BIND['tree'], datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')


def strip_root(text, root):
    """Replace the absolute repository path (as given and as resolved) with <repo> so an evidence file carries no
    host-specific checkout path. Longest spelling first."""
    for r in sorted({root.rstrip('/'), os.path.realpath(root).rstrip('/')}, key=len, reverse=True):
        if len(r) > 1:
            text = text.replace(r, '<repo>')
    return text


def evidence_header(subj, kind, status, cases, failed, rc, cmd, extra, head, tree, ts, limit='-', dirty=None):
    """Line 1: subject kind status cases failed rc (compared field by field with the TSV row). Line 2: head tree ts limit
    dirty dirtydigest. Then, in the SEALED region (everything after line 1 hashes into the TSV `evsha` column): cmd, a
    `recorded:` line repeating status/cases/failed/rc (so the body states the same verdict as the header and the TSV),
    the dirty paths when dirty, the extra block (failing tests, unbuilt packages), `---`, and the captured output."""
    d = dirty or {'dirty': 0, 'digest': '-', 'paths': []}
    dp = ''
    if d['dirty']:
        sh = d['paths'][:20]
        dp = 'dirty-paths (%d%s): %s\n' % (len(d['paths']), '; first 20 shown' if len(d['paths']) > 20 else '', ', '.join(sh))
    return ('subject=%s kind=%s status=%s cases=%s failed=%s rc=%s\nhead=%s tree=%s ts=%s limit=%s dirty=%s dirtydigest=%s\n'
            'cmd=%s\nrecorded: status=%s cases=%s failed=%s rc=%s\n%s%s\n---\n'
            % (subj, kind, status, cases, failed, rc, head, tree, ts, limit, d['dirty'], d['digest'], cmd, status, cases, failed, rc, dp, extra))


def evidence_text(subj, kind, status, cases, failed, rc, cmd, extra, head, tree, ts, limit, dirty, body):
    return evidence_header(subj, kind, status, cases, failed, rc, cmd, extra, head, tree, ts, limit, dirty) + body + '\n'


def body_sha(text):
    """sha256 of the SEALED region of an evidence file: everything after line 1. `tail -n +2 <file> | sha256sum` in the
    generator reads the same bytes."""
    return hashlib.sha256(text.split('\n', 1)[1].encode()).hexdigest()


def gate_failed(rc, out):
    """Failed-case count of a root GATE script, best effort. A gate that exits 0 has no failed result of its
    own: FAIL/failed lines in its output belong to its golden-bad (must-detect) arms and are NOT failures.
    Only a non-zero rc makes the parsed count meaningful; rc itself stays authoritative either way."""
    if rc == 0:
        return 0
    return max([int(x) for x in re.findall(r'(\d+) (?:FAIL(?:ED)?|DRIFT|DEFECT|failed)\b', out)] or [0])


def jl(**kw):
    return json.dumps(kw)


def selftest():
    ok = True

    def chk(name, cond):
        nonlocal ok
        print('  %s %s' % ('PASS' if cond else 'FAIL', name))
        ok = ok and cond
    agg = aggregate_unit([{'rc': 0, 'p': 10, 'f': 0, 's': 1}, {'rc': 1, 'p': 57, 'f': 62, 's': 0}])
    chk('aggregate_unit keeps the worst rc (1) from a module with 62 failed cases, not 0', agg['rc'] == 1 and agg['failed'] == 62 and agg['passed'] == 67)
    chk('aggregate_unit: a timeout rc 124 outranks rc 1', aggregate_unit([{'rc': 1, 'p': 1, 'f': 1, 's': 0}, {'rc': 124, 'p': 0, 'f': 0, 's': 0}])['rc'] == 124)
    chk('aggregate_unit of all-green modules is rc 0', aggregate_unit([{'rc': 0, 'p': 3, 'f': 0, 's': 0}])['rc'] == 0)
    chk('classify: 119 cases, 62 failed => check-red', classify(119, 62, 1) == 'check-red')
    chk('classify: cases>0 failed 0 rc 1 => check-red', classify(5, 0, 1) == 'check-red')
    chk('classify: cases>0 failed 0 rc 0 => check', classify(5, 0, 0) == 'check')
    chk('classify: zero cases => gap', classify(0, 0, 0) == 'gap')
    chk('gate_failed: rc 0 with a golden-bad arm printing "4 FAIL" is NOT 4 failures', gate_failed(0, '2 PASS / 4 FAIL / 0 SKIP of 6') == 0)
    chk('gate_failed: rc 1 reports the parsed failed count', gate_failed(1, '9 PASS / 3 FAIL') == 3)
    h = evidence_header('s', 'unit', 'check', 3, 1, 1, 'c', 'x', 'a' * 40, 'b' * 64, '2026-10-12T00:00:00Z', 600)
    first, second = h.splitlines()[:2]
    chk('evidence header line 1 binds subject/kind/cases/failed/rc', 'subject=s kind=unit' in first and 'cases=3 failed=1 rc=1' in first)
    chk('evidence header line 2 binds head/tree/ts, records the limit and the dirty flag', second == 'head=%s tree=%s ts=2026-10-12T00:00:00Z limit=600 dirty=0 dirtydigest=-' % ('a' * 40, 'b' * 64))

    # F2: environment build failures are not test failures
    ok_run = [jl(Action='pass', Package='m/ok', Test='TestA'), jl(Action='pass', Package='m/ok', Test='TestB'), jl(Action='pass', Package='m/ok')]
    env_goproxy = [jl(ImportPath='github.com/segmentio/kafka-go', Action='build-output', Output='internal/k/b.go:11:2: module lookup disabled by GOPROXY=off\n'),
                   jl(ImportPath='github.com/segmentio/kafka-go', Action='build-fail'),
                   jl(Action='output', Package='m/bad', Output='FAIL\tm/bad [build failed]\n'),
                   jl(Action='fail', Package='m/bad', FailedBuild='github.com/segmentio/kafka-go')]
